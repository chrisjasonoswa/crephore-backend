using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using Crephore.Api.Common.Constants;
using Crephore.Api.Data.IEntities;

namespace Crephore.Api.Data.Entities;

/*
 * A file uploaded for an event, e.g. a photo for its website. The file itself is in IFileStorage under
 * StorageKey; its URL comes from the storage (IFileStorage.GetUrl), so it follows the storage's address.
 * Deleted with its event.
 */
[Table("media")]
public class Media : IHasCreatedAt
{
    public int Id { get; set; }

    public MediaType Type { get; set; }
    public MediaPurpose Purpose { get; set; }

    // Path in the storage, e.g. "events/12/3f2a….jpg"; generated by the API, never the uploader's file name
    [MaxLength(255)]
    public string StorageKey { get; set; } = null!;
    [MaxLength(64)]
    public string ContentType { get; set; } = null!;
    public long SizeBytes { get; set; }

    // Timestamp
    public DateTimeOffset CreatedAt { get; set; }

    /* Related Properties */
    public int EventId { get; set; }
    public Event Event { get; set; } = null!;

    // Who uploaded it; null once that user is deleted
    public int? UploaderUserId { get; set; }
    public AppUser? UploaderUser { get; set; }
}

using Microsoft.Extensions.Options;

namespace Crephore.Api.Common.Storage;

// Files in a local folder, served by the API itself (WebApplicationExtensions.UseLocalFileStorage).
// For local development only: the files live on this machine.
public class LocalFileStorage(
    IOptions<StorageOptions> options,
    IWebHostEnvironment environment,
    IHttpContextAccessor httpContextAccessor
) : IFileStorage
{
    private readonly LocalStorageOptions _options = options.Value.Local;
    private readonly IHttpContextAccessor _httpContextAccessor = httpContextAccessor;
    private readonly string _rootPath = GetRootPath(options.Value.Local, environment);

    public static string GetRootPath(LocalStorageOptions options, IWebHostEnvironment environment) =>
        Path.GetFullPath(Path.Combine(environment.ContentRootPath, options.RootPath));

    public async Task SaveAsync(string key, Stream content, string contentType, CancellationToken cancellationToken = default)
    {
        var path = ResolvePath(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);

        await using var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write);
        await content.CopyToAsync(file, cancellationToken);
    }

    public Task DeleteAsync(string key, CancellationToken cancellationToken = default)
    {
        File.Delete(ResolvePath(key));
        return Task.CompletedTask;
    }

    public string GetUrl(string key) => $"{PublicBaseUrl().TrimEnd('/')}/{key}";

    private string PublicBaseUrl()
    {
        var request = _httpContextAccessor.HttpContext?.Request;
        return _options.PublicBaseUrlFromRequest && request is not null
            ? $"{request.Scheme}://{request.Host}{request.PathBase}{_options.RequestPath}"
            : _options.PublicBaseUrl;
    }

    // Keys are generated by the API, but never let one point outside the folder
    private string ResolvePath(string key)
    {
        var path = Path.GetFullPath(Path.Combine(_rootPath, key));
        if (!path.StartsWith(_rootPath + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new ArgumentException("The storage key must stay inside the storage folder.", nameof(key));
        return path;
    }
}
